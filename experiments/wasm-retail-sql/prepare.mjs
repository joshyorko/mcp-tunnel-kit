import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const provenance = JSON.parse(await readFile('provenance.json', 'utf8'));
const wasm = await readFile('node_modules/sql.js/dist/sql-wasm.wasm');
if (createHash('sha256').update(wasm).digest('hex') !== provenance.wasm.sha256) {
  throw new Error('Pinned WASM artifact hash mismatch');
}
// Emscripten mistakes workerd's WorkerGlobalScope for a browser Web Worker,
// then reads the nonexistent self.location.href. Static instantiation needs
// neither its browser loader nor its Node loader. Remove both at build time.
await build({
  entryPoints: ['node_modules/sql.js/dist/sql-wasm.js'],
  outfile: 'sqlite-glue.js', bundle: true, minify: true, format: 'esm',
  platform: 'browser', target: 'es2022',
  define: { process: 'undefined', WorkerGlobalScope: 'undefined' },
  external: ['fs', 'path', 'crypto'],
  banner: { js: '// Generated by prepare.mjs from sql.js@1.13.0; see SQLJS-LICENSE.' },
});
await writeFile('SQLJS-LICENSE', await readFile('node_modules/sql.js/LICENSE'));
